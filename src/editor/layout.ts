/** Arrange existing editors without replacing their nodes, values or event handlers. */
export function mountEditorLayout(): void {
  const palette = document.getElementById("palette");
  const calculations = document.getElementById("calculationEditor");
  if (palette && calculations) {
    palette.after(calculations);
    const heading = palette.previousElementSibling;
    if (heading?.tagName === "H3") heading.textContent = "チャットパレット";
  }
  if (!document.getElementById("resizableEditors")) {
    const style = document.createElement("style"); style.id = "resizableEditors";
    style.textContent = `
#statusEdit, #paramsEdit, #vars, #palette { display:block; resize:both; overflow:auto; min-width:12rem; min-height:6rem; max-width:100%; }
@media (hover:hover) and (pointer:fine) { #statusEdit, #paramsEdit, #vars, #palette { max-width:calc(100vw - 32px); } }
`;
    document.head.append(style);
  }
  const help = document.getElementById("usageInstructions");
  if (!help) return;
  // Static application help only. Sheet text is never inserted into this HTML.
  help.innerHTML = `<h2 style="margin-top:0">使い方</h2>
  <ol>
    <li>ゆとシートⅡのURLを入力して、<strong>出力</strong>を押します。</li>
    <li>必要に応じて、ステータス・パラメータ・チャットパレットを編集し、式に加える補正を選びます。</li>
    <li><strong>ココフォリアJSONをコピー</strong>を押すと、編集内容を反映したJSONがコピーされます。</li>
    <li>ココフォリアの盤面で右クリックし、<strong>クリップボードから貼り付け</strong>でキャラクターコマを作成します。</li>
  </ol>
  <h3>編集欄について</h3>
  <p>ステータスは1行に「ラベル 現在値 最大値」、パラメータは1行に「ラベル 値」を入力します。区切りにはタブ、半角スペース、カンマ、スラッシュ、= が使えます。スペース区切りでは、ラベルや値の途中にスペースを入れないでください。</p>
  <p>行を削除・追加すると、その項目を削除・追加できます。行の順番を入れ替えると表示順も変わります。チャパレ用変数の一覧は、チャットパレットへコピーして式を編集するためのものです。未登録の変数を使う場合は、対応するステータスやパラメータも追加してください。</p>
  <p>PCでは、ステータス・パラメータ・チャパレ用変数・チャットパレットの各欄の右下をドラッグして、横幅と高さを調整できます。ブラウザによって対応状況が異なります。調整した大きさは保存ファイルには含めません。</p>
  <p>編集後はページ上部またはチャットパレット下部の「ココフォリアJSONをコピー」を押してください。ココフォリアJSONの全文は、確認・直接編集するときだけ見出しを押して開けます。</p>
  <h3>パラメータ出力</h3>
  <p>「ゆとシートのデフォルト変数を使用する」は、最初からチェックが入っています。チェックありでは <code>命中 {器用判定}-1</code> のような参照式、チェックなしでは同じ名前のまま <code>命中 5</code> のような数値を出力します。出力する前に選んでください。ステータスにある項目はパラメータに重複させません。</p>
  <h3>ダメージ属性</h3>
  <p>武器攻撃のダメージ式の末尾は <code>{ダメージ属性}ダメージ</code> です。リソース操作欄の <code>:initiative=</code> の直下に、次の2行を出力します。</p>
  <pre style="white-space:pre-wrap">//ダメージ属性=物理
//ダメージ属性=〈〉属性魔法</pre>
  <p><strong>使わない方の行を削除し、定義を1行だけ残してからコピーしてください。</strong> 属性魔法を使う場合は、〈〉の中に地・火などの属性を記入します。同じ名前の定義が2行残っていると、「変数を確認」で重複として表示されます。</p>
  <p>これはダメージの表示名を決める設定です。理力符などの使用宣言だけでは属性は切り替わりません。ダメージの数値や、適用する防御力は別に確認してください。所持数を減らすときは、該当する消費コマンドを使います。</p>
  <h3>プリプレイ宣言と同時使用スキル</h3>
  <p>タイミングが「アイテム」のスキルと、効果文が「プリプレイで」から始まるスキルは、判定とパッシブの間にあるプリプレイ欄へまとめます。<code>《ファミリア》1：効果文</code> のように、スキル名の後ろにスキルレベルを表示します。1行の中に改行用の <code>\\n</code> を入れているため、一つの宣言として送れます。</p>
  <p>タイミングが《スキル名》のものと、効果文に「《スキル名》と同時に使用する」と明記されたスキルは、元のタイミングにかかわらず、そのスキルの宣言・消費・判定・効果ロールの下に並びます。同時使用先が複数、未取得、同名が複数、参照が循環する場合は推測せず、元のタイミングに残して警告します。</p>
  <h3>消耗品の自動出力</h3>
  <p>次の表形式でアイテム欄を記入した場合のみ、消耗品の名前・個数・使用タイミング・効果のロールをまとめて自動出力します。列の順番は「名前｜個数｜効果｜説明｜重量」です。効果欄の先頭に使用タイミングを書き、同じ欄に「消耗品」を含めてください。名前は略さず、記入した名前を使います。</p>
  <pre style="white-space:pre-wrap;overflow-wrap:anywhere">|ハイHPポーション|3|マイナーアクション、メジャーアクション。HP回復を行なう。使用者の【HP】を［4D］点回復する。消耗品。|効果の高いHPポーション。|@[1*3]|</pre>
  <p>この例では、<strong>ステータス欄に「ハイHPポーション 3 0」</strong>が入り、所持数3個・最大値0として管理できます。<strong>チャットパレットの「マイナー」と「メジャー」の両方</strong>に、使用宣言、所持数を1個減らす <code>:ハイHPポーション-1</code>、回復量を求める <code>4D ハイHPポーション</code> が出力されます。</p>
  <p>読み取れた消耗品の管理ステータスは「ダメバフ」の直下にまとめます。└・┗などの行頭の罫線と重量指定は個数に数えません。同じ名前・効果の行は個数を合計し、個数0と書いたものは0のまま扱います。</p>
  <p><code>HPP*3</code> などの簡易表記は個数だけを読み取ります。使用タイミングと効果が書かれていないため、使用コマンドや回復量の式は手で追加してください。所持品として読み取れなかった消耗品のステータスや、使用コマンドのひな形は出力しません。</p>
  <p>表の使用タイミングや個数を読み取れない行は自動出力せず、警告します。回復量だけ読めない場合は使用宣言と消費コマンドを出し、ロールは要確認として残します。自動で出力されなかった項目は、ステータスやチャットパレットで手入力できます。</p>
  <h3>判定・ダメージ・回復量の補正</h3>
  <p>効果文から読み取れた魔法攻撃のダメージやHP・MPの回復量は、スキルの判定式の下に出力します。プロテクションやディスコードの効果、レイズのHPは、<code>5D プロテクション</code>、<code>2D レイズ</code> のようにスキル名を付けて出します。ダイス数は効果文とスキルレベルから求め、読めない量は推測しません。</p>
  <p>チャットパレット下の「式に加える補正」で対象の式を開き、加える補正を選びます。ダメージと判定の一覧は最初は閉じています。新規出力ではダメージ補正は選択済み、判定・回復量・スキルの効果の補正は未選択です。保存した編集を開く場合は、保存時の選択を使います。</p>
  <p><strong>ゆとシートの合計値に含めている補正は、二重に加算しないようチェックを外してください。</strong> スキルレベルは数値として計算し、CLや能力値は変数のまま残します。攻撃用・HP回復用・MP回復用の補正は分けて扱い、「HPを○点にする」効果に通常の回復量増加を加えることはありません。</p>
  <p>補正のチェックは、式に組み込む操作です。「常時加算」はそのまま足し、「0・1で切り替え」は必要なステータスを現在値0・最大値0で追加します。卓中は1にすると有効、0にすると無効です。装備は効果文のタイミングがパッシブなら常時加算、DRの直前・直後や効果参照などなら0・1方式を初期値にします。条件付きのパッシブも含め、適用条件に合わせて選び直してください。</p>
  <p>「0・1で切り替え」の下の「変数名を変更」から、WBなどの短い名前を指定できます。式・ステータス・変数一覧に反映し、スキルの使用回数を管理する名前は変えません。空欄で「名前を適用」を押すと元の名前に戻ります。</p>
  <p>単独の能力値を掛ける式は <code>{スマッシュ}*{筋力}</code>、合計を掛ける式は <code>{補正}*({筋力}+3)</code> のように出します。能力値を数値ではなく複合式に手で変更する場合は、計算順も確認してください。</p>
  <p>同じ内容の共通判定は一つの補正欄にまとめています。スキル固有の判定や元の式・適用対象が異なるものは別です。各行の選択が異なる場合は混在として表示し、変更した補正から共通の設定にします。</p>
  <h3>すべての判定への一括加算</h3>
  <p>「あらゆる判定」などの補正は、判定の補正欄の先頭で、すべての判定へのチェックをまとめてオン・オフできます。不要な判定だけ、後から個別に外してください。一部だけ選んだ状態も一括チェックに表示します。加算方法や短縮名、ダメージ・回復量の選択は変更しません。</p>
  <p>チェック操作は対象の式だけを変更します。手で直した式は一括操作でも上書きせず、候補式を表示します。追加した切り替え用ステータスは、チェックを外しても残ります。不要なものはステータス欄で削除してください。</p>
  <h3>精神判定と強心丹</h3>
  <p>精神判定には補正用ステータス <code>強心丹D</code> を加えています。使用後は1、効果が終わったら0にします。所持数を管理する「強心丹」とは別の項目です。「あらゆる判定」の補正は判定だけに適用し、ダメージや回復量には加えません。</p>
  <p>リソース操作には精神判定（リアクション）も出します。《ベアアップ》（ペアアップ表記にも対応）を取得している場合だけ、この式に+1Dします。この式はスキルに対するリアクション用です。通常の精神判定には加えず、二重加算を防ぐため補正候補にも出しません。</p>
  <h3>確認と手入力</h3>
  <p>「変数を確認」では、未登録の変数、名前の重複、参照の循環、消費コマンドの操作先などを確認できます。コピー時にも確認しますが、入力を勝手に修正したりコピーを止めたりはしません。「この行を編集」から該当箇所へ移動できます。</p>
  <p>ゲームのルール、ルーム側の変数、補正の二重加算までは確認できません。別のスキルの効果を書き換えるものや、複雑な適用条件は原文を確認して手入力してください。再出力は編集を作り直す操作です。編集を残してキャラシを読み直す場合は「更新を反映」を使ってください。</p>`;
}
