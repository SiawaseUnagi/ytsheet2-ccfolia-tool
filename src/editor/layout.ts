/** Arrange existing editors without replacing their nodes, values or event handlers. */
export function mountEditorLayout(): void {
  const palette = document.getElementById("palette");
  const calculations = document.getElementById("calculationEditor");
  if (palette && calculations) {
    (document.getElementById("editorTools") ?? palette).after(calculations);
    const heading = palette.previousElementSibling;
    if (heading?.tagName === "H3") heading.textContent = "チャットパレット";
  }
  if (!document.getElementById("resizableEditors")) {
    const style = document.createElement("style"); style.id = "resizableEditors";
    style.textContent = `
#statusEdit, #paramsEdit, #vars, #palette { display:block; resize:both; overflow:auto; min-width:12rem; min-height:6rem; max-width:100%; }
@media (hover:hover) and (pointer:fine) { #statusEdit, #paramsEdit, #vars, #palette { max-width:calc(100vw - 32px); } }
#usageInstructions pre { white-space:pre-wrap; overflow-wrap:anywhere; }
#usageInstructions blockquote { margin:12px 0; padding:8px 12px; border-left:3px solid #ccc; }
`;
    document.head.append(style);
  }
  const help = document.getElementById("usageInstructions");
  if (!help) return;
  // Static help is mounted after the editor tools so there is only one complete guide.
  help.innerHTML = `<h2 style="margin-top:0">アリアンロッド2E ココフォリア駒作成ツール 使い方</h2>
<p>ゆとシートⅡのキャラクターシートから、ココフォリア用の駒データ（ステータス・パラメータ・チャットパレット）を一括生成するツールです。</p>
<h3>基本の手順（クイックスタート）</h3>
<ol>
<li><strong>設定の確認</strong><p>「ゆとシートのデフォルト変数を使用する」にチェックを入れると <code>{器用判定}-1</code> のような参照式、外すと <code>5</code> のような固定値で出力されます。初期設定はチェックありです。<strong>出力後もチェックを切り替えるだけで、自動生成されたパラメータの参照式と固定値を切り替えられます。</strong> URLの再読み込みや再出力は不要です。手編集した判定値・数式はそのまま残し、切り替えなかった項目を表示します。</p></li>
<li><strong>データの出力</strong><p>ゆとシートⅡのURLを入力し、［出力］ボタンを押します。</p></li>
<li><strong>必要に応じた調整</strong><p>画面下部の「式に加える補正」やチャットパレットを確認・編集します。</p><p>ダメージ属性の選択：チャットパレット内の <code>:initiative=</code> の直下にある <code>//ダメージ属性=物理</code> と <code>//ダメージ属性=〈〉属性魔法</code> を確認し、基本は使わない方の1行を削除してください。属性魔法の場合は〈〉内に火・水などを入力します。</p><blockquote><strong>Tips：戦闘中に物理と属性魔法を切り替えたい場合</strong><p>両行をココフォリアへ持ち込む場合は、使わない方を <code>//_ダメージ属性=...</code> のように別名にしておきます。卓中に切り替えるときは、使う方を <code>//ダメージ属性=...</code>、使わない方を <code>//_ダメージ属性=...</code> に変更してください。<code>ダメージ属性</code> の定義は常に1行だけにします。これはチャパレ編集欄で定義を書き換える操作で、宣言を送信するだけでは切り替わりません。</p></blockquote></li>
<li><strong>ココフォリアへの取り込み</strong><p>［ココフォリアJSONをコピー］を押し、ココフォリアの盤面上で右クリック →「クリップボードから貼り付け」を実行します。</p></li>
</ol>
<h3>編集欄の使い方</h3>
<ul>
<li><strong>ステータス・パラメータ</strong><p>1行に「ラベル 現在値 最大値」（パラメータは「ラベル 値」）の形式で記載します。スペース・タブ・カンマ等で区切り、行の追加・削除・並び替えができます。スペース区切りではラベルや値の途中にスペースを入れないでください。</p></li>
<li><strong>チャパレ用変数</strong><p>チャットパレット内で使用する変数の一覧です。式を手動編集する際の参照用としてお使いください。スキルの変数候補には未登録のものもあるため、使用するときは対応するステータスやパラメータを追加してください。</p></li>
<li><strong>表示サイズの変更</strong><p>PC環境では、各枠の右下をドラッグして広げることができます。ブラウザによって対応が異なり、表示サイズは保存データには反映されません。</p></li>
</ul>
<p>［変数を確認］では、未登録の変数や名前の重複などを確認できます。ゲームのルールや補正の二重加算までは判定しません。</p>
<h3>便利な自動処理機能</h3>
<h4>消耗品の自動パレット化</h4>
<p>ゆとシートⅡのアイテム欄を以下の表形式（名前｜個数｜効果｜説明｜重量）で記入しておくと、所持数をステータスに、使用コマンドや回復ロールをチャットパレットへ自動展開します。</p>
<pre>|ハイHPポーション|3|マイナーアクション、メジャーアクション。HP回復を行なう。使用者の【HP】を［4D］点回復する。消耗品。|効果の高いHPポーション。|@[1*3]|</pre>
<p>「効果」欄の先頭に使用タイミングを書き、同じ欄内に「消耗品」の文言を含めてください。</p>
<p>この例では、<strong>ステータス欄に「ハイHPポーション 3 0」</strong>が入り、<strong>チャットパレットの「マイナー」と「メジャー」の両方</strong>に使用宣言、<code>:ハイHPポーション-1</code>、<code>4D ハイHPポーション</code> が出力されます。</p>
<p><code>HPP*3</code> などの簡易表記は個数だけを読み取ります。使用タイミングや個数が読めない表の行は自動出力せず、回復量だけ読めない場合は宣言と消費コマンドまで出力します。足りない項目は手入力してください。</p>
<h4>スキルの同時使用・プリプレイまとめ</h4>
<p>タイミング欄が《スキル名》のものや、効果文に「《スキル名》と同時に使用する」とあるスキルは、対象スキルの直下に自動配置されます。対象を一つに決められない場合は移動せず警告します。</p>
<p>タイミングが「アイテム」のスキルや、効果文が「プリプレイで〜」から始まるスキルは、「判定」と「パッシブ」の間のプリプレイ欄へ集約します。<code>《ファミリア》1</code> のようにレベルを表示し、文字としての <code>\\n</code> でつないだ1行の宣言を作ります。</p>
<h4>特殊な補正（強心丹・ベアアップなど）</h4>
<p>精神判定には、使用時にオン・オフできる <code>強心丹D</code> ステータスを自動付与しています。卓中に1へ変更すると有効になり、効果が終わったら0に戻します。</p>
<p>スキル《ベアアップ》習得時は、スキルに対するリアクション用の精神判定式に自動で+1Dが加算されます。通常の精神判定には加算しません。</p>
<h3>式に加える補正の設定</h3>
<p>チャットパレット下の「式に加える補正」から、各判定・ダメージ・回復量などに加えるスキルや装備の補正を選べます。<strong>すべての一覧は、最初は閉じています。</strong> 設定するときは見出しを押して開いてください。新規出力ではダメージ補正は選択済み、判定・回復量・スキルの効果の補正は未選択です。閉じていても選択済みの補正は反映されます。</p>
<ul>
<li><strong>常時加算</strong>：パッシブスキルなど、常に式に数値を加える設定です。</li>
<li><strong>フラグ管理（ON/OFF切り替え）</strong>：補正を管理するステータス（初期値0）を作成し、セッション中にステータスを1へ書き換えると補正が有効になる設定です。0に戻すと無効になります。「変数名を変更」から、ステータス名をWBなどの短い略称に変更できます。</li>
<li><strong>一括加算</strong>：「あらゆる判定」などの全体補正は、判定の先頭にあるチェックで、すべての判定式への補正の選択をまとめてオン・オフできます。不要な判定だけ個別に外せます。加算方法や卓中のフラグの値は変更しません。</li>
</ul>
<blockquote><p>ゆとシート側ですでに合計値に含めている補正は、二重加算にならないようチェックを外してください。</p><p>フラグ管理で一度生成されたステータスは、後からチェックを外してもステータス欄に残ります。不要な場合は手動でステータス行を削除してください。</p><p>手編集した式はチェック操作で上書きせず、候補式を表示します。必要な部分だけコピーして反映してください。</p></blockquote>
<h3>データの保存と更新</h3>
<h4>ブラウザに保存 / 続きから編集</h4>
<p>編集作業が終わったら［このブラウザに保存］を押してください。自動保存ではありません。次回アクセス時は一覧からキャラを選び、［続きから編集］で再開できます。変数の出力方式、補正の選択や短縮名、手編集した文章も保存します。</p>
<p>ブラウザの「Cookie・サイトデータ」を削除すると保存内容も消去されます。画像などのキャッシュとは別の保存領域を使っています。別端末や別ブラウザには自動共有されません。シークレット・プライベートモードでは保存が失われることがあるため、重要なデータはファイル書き出し機能でバックアップしてください。保存ファイルにはキャラシと編集内容が含まれるので、共有する際は内容を確認してください。</p>
<h4>キャラシの更新を反映（レベルアップ時など）</h4>
<p>ゆとシート側を更新した後は［更新を反映］を押します。手動で編集した箇所を維持しながら、新しい能力値・スキル・所持数を取り込みます。同じ箇所が手編集とキャラシの両方で変わった場合は、残す内容を選びます。確認後、［この内容で更新・保存］で確定してください。</p>
<p>更新時はHP・MP・フェイト・スキルの使用回数を新しい最大値にそろえ、一時的な補正を0に戻します。［続きから編集］で開くだけでは現在値を変更しません。［更新前に戻す］では直前の更新を取り消せます。［出力］は編集内容を作り直す操作なので、編集を残す場合は［更新を反映］を使ってください。</p>`;
}
